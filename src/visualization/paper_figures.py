def _apply_theme() -> None:
    # AAAI rejects Type 3 fonts even inside figures; embed TrueType as Type 42.
    plt.rcParams.update(
        {
            "font.family": "serif",
            "font.serif": ["Times New Roman", "Times", "DejaVu Serif"],
            "mathtext.fontset": "stix",
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "svg.fonttype": "none",
            "axes.facecolor": "white",
            "figure.facecolor": "white",
            "savefig.facecolor": "white",
            "axes.edgecolor": SPINE,
            "axes.linewidth": 0.9,
            "xtick.color": TEXT,
            "ytick.color": TEXT,
            "text.color": TEXT,
            "axes.labelcolor": TEXT,
            "font.size": 11,
            "axes.labelsize": 12,
            "axes.titlesize": 12,
            "xtick.labelsize": 10,
            "ytick.labelsize": 10,
            "legend.fontsize": 10,
        }
    )


def _neurips_axes(ax, *, grid_y: bool = True, grid_x: bool = False) -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["left"].set_linewidth(0.8)
    ax.spines["bottom"].set_linewidth(0.8)
    ax.spines["left"].set_color(SPINE)
    ax.spines["bottom"].set_color(SPINE)
    ax.tick_params(colors=TEXT, width=0.8, length=3)
    if grid_y:
        ax.grid(True, axis="y", linestyle="-", linewidth=0.4, color=GRID, alpha=0.7)
    if grid_x:
        ax.grid(True, axis="x", linestyle="-", linewidth=0.4, color=GRID, alpha=0.7)
    ax.set_axisbelow(True)


def _annotate_bars(
    bars,
    *,
    min_h: float = 0.0,
    fontsize: float = 8.0,
    dy: float = 1.0,
    rotation: float = 0.0,
    fmt: str | None = None,
) -> None:
    """Value labels above bars. ``min_h=0`` labels every finite bar (incl. short FPR)."""
    for bar in bars:
        v = float(bar.get_height())
        if not np.isfinite(v) or v < min_h:
            continue
        ax = bar.axes
        if fmt is None:
            lab = f"{v:.1f}" if v < 10 else f"{v:.0f}"
        else:
            lab = fmt.format(v)
        ax.text(
            bar.get_x() + bar.get_width() / 2,
            v + dy,
            lab,
            ha="center",
            va="bottom",
            fontsize=fontsize,
            color=TEXT,
            rotation=rotation,
            clip_on=False,
            zorder=5,
        )


def _legend_above(ax_or_fig, handles=None, labels=None, *, ncol: int = 2, fontsize: int = 10):
    kwargs = dict(
        frameon=False,
        fontsize=fontsize,
        loc="lower center",
        bbox_to_anchor=(0.5, 1.0),
        ncol=ncol,
        borderaxespad=0.0,
        handlelength=1.2,
        columnspacing=1.2,
    )
    if handles is not None:
        return ax_or_fig.legend(handles, labels, **kwargs)
    return ax_or_fig.legend(**kwargs)


def _save(fig, path: Path, *, dpi: int = 300) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    # Re-assert Type 42 embedding (AAAI rejects Type 3 fonts in figures).
    plt.rcParams["pdf.fonttype"] = 42
    plt.rcParams["ps.fonttype"] = 42
    kwargs = dict(bbox_inches="tight", pad_inches=0.04, facecolor="white")
    fig.savefig(path, format="pdf", **kwargs)
    fig.savefig(path.with_suffix(".png"), dpi=dpi, **kwargs)
    plt.close(fig)
    print(f"[OK] Saved: {path}")
    return path


def _matched_rows() -> pd.DataFrame:
    path = RESULTS_DIR / "matched_fpr" / "metrics.csv"
    m = pd.read_csv(path)
    m.columns = [c.strip() for c in m.columns]
    matched = m[m["mode"].astype(str).str.startswith("matched_fpr")].copy()
    matched["method"] = matched["method"].astype(str).str.strip()
    order = {k: i for i, k in enumerate(METHOD_ORDER)}
    matched["_ord"] = matched["method"].map(lambda x: order.get(x, 99))
    return matched.sort_values("_ord")


def plot_pipeline(out: Path | None = None) -> Path:
    """Schematic: prompt → gate → (block | target → judge)."""
    _apply_theme()
    out = out or (IMAGES_DIR / "pipeline.pdf")
    fig, ax = plt.subplots(figsize=COL_SIZE)
    ax.set_xlim(0, 12)
    ax.set_ylim(0, 4)
    ax.axis("off")

    def box(x, y, w, h, text, *, fc="#F5F5F5", ec=SPINE, fs=8.5):
        patch = FancyBboxPatch(
            (x, y),
            w,
            h,
            boxstyle="round,pad=0.04,rounding_size=0.12",
            linewidth=1.0,
            edgecolor=ec,
            facecolor=fc,
        )
        ax.add_patch(patch)
        ax.text(
            x + w / 2,
            y + h / 2,
            text,
            ha="center",
            va="center",
            fontsize=fs,
            color=TEXT,
        )

    def arrow(x1, y1, x2, y2):
        ax.annotate(
            "",
            xy=(x2, y2),
            xytext=(x1, y1),
            arrowprops=dict(arrowstyle="-|>", color=SPINE, lw=1.2),
        )

    box(0.2, 1.5, 1.8, 1.0, "User prompt")
    arrow(2.05, 2.0, 2.55, 2.0)
    box(2.55, 1.35, 2.3, 1.3, "Pre-inference\ngate $g(x)$", fc="#E8ECF4", ec=BLUE)
    arrow(4.9, 2.35, 5.55, 3.15)
    arrow(4.9, 1.65, 5.55, 0.85)
    box(5.55, 2.75, 2.0, 0.85, "Blocked\n(no model call)", fc="#F4E8E9", ec=RED)
    box(5.55, 0.4, 2.0, 0.95, "Allowed\nforward", fc="#E8ECF4", ec=BLUE)
    arrow(7.6, 0.9, 8.15, 0.9)
    box(8.15, 0.4, 1.85, 0.95, "Target LLM\n(Qwen2.5-3B)")
    arrow(10.05, 0.9, 10.5, 0.9)
    box(10.5, 0.4, 1.35, 0.95, "Judge\ncomply?")

    ax.text(
        6.55,
        3.75,
        "Layer 1 - Bypass Rate",
        ha="center",
        va="center",
        fontsize=8.5,
        color=RED,
        fontweight="bold",
    )
    ax.text(
        9.9,
        1.55,
        "Layer 2 - True ASR",
        ha="center",
        va="center",
        fontsize=8.5,
        color=BLUE,
        fontweight="bold",
    )
    ax.text(
        6.0,
        0.12,
        r"TrueASR $= |\{x\in\mathcal{I}: g(x)=0 \wedge \mathrm{comply}(x)=1\}|\,/\,|\mathcal{I}|$",
        ha="center",
        va="bottom",
        fontsize=7,
        color=TEXT,
    )
    return _save(fig, out)


def _plot_method_schematic(
    out: Path,
    *,
    title: str,
    stages: list[tuple[str, str]],
    footer: str,
    accent: str,
) -> Path:
    _apply_theme()
    fig, ax = plt.subplots(figsize=COL_SIZE_TALL)
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 12)
    ax.axis("off")
    ax.set_title(title, fontsize=12, color=TEXT, pad=6)
    y = 10.6
    for i, (label, fc) in enumerate(stages):
        h = 1.45 if i < len(stages) - 1 else 1.55
        patch = FancyBboxPatch(
            (0.8, y - h),
            8.4,
            h,
            boxstyle="round,pad=0.05,rounding_size=0.15",
            linewidth=1.1,
            edgecolor=accent if i in (1, 2) else SPINE,
            facecolor=fc,
        )
        ax.add_patch(patch)
        ax.text(
            5.0,
            y - h / 2,
            label,
            ha="center",
            va="center",
            fontsize=10,
            color=TEXT,
        )
        if i < len(stages) - 1:
            ax.annotate(
                "",
                xy=(5.0, y - h - 0.32),
                xytext=(5.0, y - h - 0.04),
                arrowprops=dict(arrowstyle="-|>", color=SPINE, lw=1.1),
            )
        y -= h + 0.42
    ax.text(5.0, 0.3, footer, ha="center", va="center", fontsize=8.5, color=TEXT)
    return _save(fig, out)


