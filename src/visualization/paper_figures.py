    asr_plot = np.where(np.isnan(asr), 0.0, asr)
    asr_mask = ~np.isnan(asr)
    b2 = ax.bar(
        x[asr_mask] + width / 2 + gap / 2,
        asr_plot[asr_mask],
        width,
        color=RED,
        edgecolor="white",
        linewidth=0.6,
        label="True ASR",
        zorder=3,
    )
    _annotate_bars(b1, min_h=5.0, fontsize=8, dy=1.0, rotation=90)
    _annotate_bars(b2, min_h=5.0, fontsize=8, dy=1.0, rotation=90)

