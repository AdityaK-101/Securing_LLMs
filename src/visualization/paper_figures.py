    a = pd.read_csv(RESULTS_DIR / "loo_matched_fpr" / "robustness_adaptive.csv")
    a.columns = [c.strip() for c in a.columns]

    from ..evaluation.loo_matched_fpr import LOO_SOURCE_FOLDS

    # Prefer precomputed macro; else mean over four source folds.
    macro = a[a["fold"].astype(str) == "four_source_macro_avg"].copy()
    if macro.empty:
        src = a[a["fold"].isin(LOO_SOURCE_FOLDS)].copy()
        rows = []
        for method, grp in src.groupby("method"):
            row = {"method": method, "Bypass_Rate_%": float(grp["Bypass_Rate_%"].mean())}
            if "True_ASR_%" in grp.columns and grp["True_ASR_%"].notna().any():
                row["True_ASR_%"] = float(grp["True_ASR_%"].mean())
            else:
                row["True_ASR_%"] = float("nan")
            rows.append(row)
        macro = pd.DataFrame(rows)
    else:
        macro["method"] = macro["method"].astype(str).str.strip()

    order = {k: i for i, k in enumerate(METHOD_ORDER)}
    macro["_ord"] = macro["method"].map(lambda x: order.get(x, 99))
    macro = macro.sort_values("_ord")

    labels = [METHOD_SHORT.get(m, m) for m in macro["method"]]
    bypass = macro["Bypass_Rate_%"].astype(float).to_numpy()
    asr = macro["True_ASR_%"].astype(float).to_numpy() if "True_ASR_%" in macro.columns else np.full(len(macro), np.nan)

    x = np.arange(len(macro)) * 1.15
    width, gap = 0.40, 0.08
    fig, ax = plt.subplots(figsize=COL_SIZE)
    b1 = ax.bar(
        x - width / 2 - gap / 2,
        bypass,
        width,
        color=BLUE,
        edgecolor="white",
        linewidth=0.6,
        label="Bypass Rate",
        zorder=3,
    )
