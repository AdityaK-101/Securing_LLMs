def _plot_delta_panel(
    out: Path,
    *,
    labels: list[str],
    deltas: np.ndarray,
    color: str,
    ylabel: str = "Δ Bypass (percentage points)",
) -> Path:
    _apply_theme()
    fig, ax = plt.subplots(figsize=COL_SIZE)
    x = np.arange(len(labels))
    colors = [color if v >= 15 else SLATE for v in deltas]
    bars = ax.bar(
        x,
        deltas,
        width=0.7,
        color=colors,
        edgecolor="white",
        linewidth=0.5,
        zorder=3,
    )
    for bar, v in zip(bars, deltas):
        ax.text(
            bar.get_x() + bar.get_width() / 2,
            v + 1.5,
            f"+{v:.1f}" if v >= 0 else f"{v:.1f}",
            ha="center",
            va="bottom",
            fontsize=11,
            color=TEXT,
        )
    ax.set_xticks(x)
    ax.set_xticklabels(labels, fontsize=11)
    ax.set_ylabel(ylabel, fontsize=13)
    ax.set_ylim(0, max(95.0, float(np.max(deltas)) + 14))
    ax.axhline(0, color=SPINE, linewidth=0.8)
    _neurips_axes(ax)
    ax.tick_params(axis="y", labelsize=11)
    fig.tight_layout(pad=0.3)
    return _save(fig, out)


def plot_ablation_delta(out: Path | None = None) -> list[Path]:
    """Attribution: separate single plots for Method A and Method B Δ Bypass."""
    dest = Path(out).parent if out else IMAGES_DIR
    hard = pd.read_csv(RESULTS_DIR / "hard_trigger_ablation.csv")
    learned = pd.read_csv(RESULTS_DIR / "learned_ablation_metrics.csv")

    hard_map = [
        ("-No Semantic Hard Trigger", "− semantic\ntrigger"),
        ("-No Intent Hard Trigger", "− intent\ntrigger"),
        ("-No Roleplay+Keyword Hard Trigger", "− role-play\n+keyword"),
        ("Soft-Only A (No Hard Triggers)", "− all hard\ntriggers"),
    ]
    learned_map = [
        ("-No All Semantic", "− all\nsemantic"),
        ("-No Semantic Top3", "− top-3\nmean"),
        ("-No Semantic Max", "− semantic\nmax"),
        ("-No Semantic Contrast", "− contrast"),
        ("-No Keyword", "− keyword"),
        ("-No Intent", "− intent"),
    ]

    def _deltas(df, mapping):
        idx = {
            str(r["variant"]).strip(): float(r["Delta_Bypass_pp"])
            for _, r in df.iterrows()
        }
        labels = [lab for _, lab in mapping]
        vals = np.asarray([idx[key] for key, _ in mapping])
        return labels, vals

    h_lab, h_d = _deltas(hard, hard_map)
    l_lab, l_d = _deltas(learned, learned_map)
    return [
        _plot_delta_panel(dest / "ablation_delta_a.pdf", labels=h_lab, deltas=h_d, color=BLUE),
        _plot_delta_panel(dest / "ablation_delta_b.pdf", labels=l_lab, deltas=l_d, color=RED),
    ]


