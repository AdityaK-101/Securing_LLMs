def plot_defense_comparison(out: Path | None = None) -> Path:
    """Mixed-split matched-FPR: Bypass vs True ASR (NeurIPS theme)."""
    _apply_theme()
    out = out or (IMAGES_DIR / "defense_comparison.pdf")
    df = _matched_rows()
    labels = [METHOD_SHORT.get(m, m) for m in df["method"]]
    x = np.arange(len(df)) * 1.15
    width = 0.40
    gap = 0.08
    bypass = df["test_Bypass_Rate_%"].astype(float).to_numpy()
    asr = df["test_True_ASR_%"].astype(float).to_numpy()

    fig, ax = plt.subplots(figsize=COL_SIZE)
    b1 = ax.bar(
        x - width / 2 - gap / 2,
        bypass,
        width,
        color=BLUE,
        edgecolor="white",
        linewidth=0.6,
        label="Bypass Rate",
        zorder=3,
    )
    b2 = ax.bar(
        x + width / 2 + gap / 2,
        asr,
        width,
        color=RED,
        edgecolor="white",
        linewidth=0.6,
        label="True ASR",
        zorder=3,
    )
    _annotate_bars(b1, min_h=5.0, fontsize=8, dy=1.0, rotation=90)
    _annotate_bars(b2, min_h=5.0, fontsize=8, dy=1.0, rotation=90)

    ax.set_xticks(x)
    ax.set_xticklabels(labels, fontsize=8, rotation=35, ha="right")
    ax.set_ylim(0, 125)
    ax.set_yticks(np.arange(0, 101, 20))
    ax.set_ylabel("% of test injections", fontsize=12)
    _neurips_axes(ax)
    ax.tick_params(axis="y", labelsize=10)
    ax.tick_params(axis="x", labelsize=8)
    _legend_above(ax, fontsize=9)
    fig.tight_layout(pad=0.2)
    fig.subplots_adjust(bottom=0.22)
    return _save(fig, out)


def plot_security_usability_tradeoff(out: Path | None = None) -> Path:
    """
    Same graph as before (all-methods mixed-split True ASR vs FPR frontier),
    restyled with the NeurIPS theme (Times, #465484 / #9B2B31 accents, #ECECEC grid).
    """
    _apply_theme()
    out = out or (IMAGES_DIR / "security_usability_tradeoff.pdf")
    df = _matched_rows()
    fig, ax = plt.subplots(figsize=COL_SIZE)

    # Same points / labels / offsets; colors mapped into the NeurIPS palette.
    point_color = {
        "baseline": RED,
        "regex": "#B85A5E",
        "keyword": BLUE,
        "context_aware": BLUE,
        "context_aware_learned": RED,
        "similarity_only": SLATE,
        "deberta_finetuned": BLUE,
        "protectai": SLATE,
        "prompt_guard": "#555555",
    }
    short = {
        "baseline": "No defense",
        "regex": "Regex",
        "keyword": "Keyword",
        "context_aware": "Method A",
        "context_aware_learned": "Method B",
        "similarity_only": "Sim-only",
        "deberta_finetuned": "DeBERTa-FT",
        "protectai": "ProtectAI",
        "prompt_guard": "Prompt Guard 2",
    }
    offset = {
        "baseline": (6, -12),
        "regex": (6, 6),
        "keyword": (6, 6),
        "context_aware": (8, 8),
        "protectai": (8, -12),
        "context_aware_learned": (6, 8),
        "similarity_only": (6, 6),
        "deberta_finetuned": (6, -12),
        "prompt_guard": (6, -12),
    }

    # Draw A/B last so their NeurIPS colors stay visible when points coincide.
    rows = sorted(
        df.iterrows(),
        key=lambda item: 1 if str(item[1]["method"]) in ("context_aware", "context_aware_learned") else 0,
    )
    for _, r in rows:
        m = str(r["method"])
        x = float(r["test_FPR_%"])
        y = float(r["test_True_ASR_%"])
        is_ab = m in ("context_aware", "context_aware_learned")
        ax.scatter(
            x,
            y,
            s=95 if is_ab else 80,
            color=point_color.get(m, SLATE),
            edgecolors="white",
            linewidths=0.8,
            zorder=5 if is_ab else 4,
            marker="o",
        )
        ax.annotate(
            short.get(m, m),
            (x, y),
            textcoords="offset points",
            xytext=offset.get(m, (6, 6)),
            fontsize=10,
            color=TEXT,
            zorder=6,
        )

    ax.axvline(5.0, color=SPINE, linestyle="--", linewidth=0.9, alpha=0.7)
    ax.set_xlabel("Test FPR % (PI-benign; lower = more usable)", fontsize=12)
    ax.set_ylabel("Test True ASR % (lower = safer)", fontsize=12)
    ax.set_title(
        "Security–usability frontier (mixed split, matched FPR)",
        fontsize=13,
        color=TEXT,
        pad=8,
    )
    ax.set_xlim(-1.5, max(12.0, float(df["test_FPR_%"].max()) + 3))
    ax.set_ylim(-2, max(65.0, float(df["test_True_ASR_%"].max()) + 8))
    ax.text(
        0.2,
        2.0,
        "ideal\n(low ASR, low FPR)",
        fontsize=9,
        color=BLUE,
        ha="left",
        va="bottom",
    )
    _neurips_axes(ax, grid_y=True, grid_x=True)
    ax.tick_params(axis="both", labelsize=11)
    fig.tight_layout(pad=0.3)
    return _save(fig, out)


def plot_ablation_combined(out: Path | None = None) -> Path:
    """Two-panel ablation in NeurIPS theme (current ablation CSVs)."""
    _apply_theme()
    out = out or (IMAGES_DIR / "ablation_combined.pdf")
    hard = pd.read_csv(RESULTS_DIR / "hard_trigger_ablation.csv")
    learned = pd.read_csv(RESULTS_DIR / "learned_ablation_metrics.csv")

    hard_map = [
        ("Full Model (A + Hard Triggers)", "Full\nMethod A"),
        ("-No Semantic Hard Trigger", "− semantic\ntrigger"),
        ("-No Intent Hard Trigger", "− intent\ntrigger"),
        ("-No Roleplay+Keyword Hard Trigger", "− role-play +\nkeyword"),
        ("Soft-Only A (No Hard Triggers)", "− all hard\ntriggers"),
    ]
    learned_map = [
        ("Full Learned Model", "Full\nMethod B"),
        ("-No All Semantic", "− all semantic\nfeatures"),
        ("-No Semantic Top3", "− semantic\ntop-3 mean"),
        ("-No Semantic Max", "− semantic\nmax"),
        ("-No Semantic Contrast", "− semantic\ncontrast"),
        ("-No Keyword", "− keyword"),
    ]

    def _vals(df, mapping):
        idx = {str(r["variant"]).strip(): r for _, r in df.iterrows()}
        labels, bypass, asr = [], [], []
        for key, lab in mapping:
            r = idx[key]
            labels.append(lab)
            bypass.append(float(r["Bypass_Rate_%"]))
            asr.append(float(r["True_ASR_%"]))
        return labels, np.asarray(bypass), np.asarray(asr)

    width, gap, group = 0.34, 0.08, 1.2

    def panel(ax, labels, bypass, asr, highlight_color, annotate, *, ylabel=False):
        x = np.arange(len(labels)) * group
        b1 = ax.bar(
            x - width / 2 - gap / 2,
            bypass,
            width,
            color=BLUE,
            edgecolor="white",
            linewidth=0.5,
            label="Bypass Rate",
            zorder=3,
        )
        b2 = ax.bar(
            x + width / 2 + gap / 2,
            asr,
            width,
            color=RED,
            edgecolor="white",
            linewidth=0.5,
            label="True ASR",
            zorder=3,
        )
        for bars in (b1, b2):
            for bar in bars:
                v = bar.get_height()
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    v + 2.2,
                    f"{v:.1f}",
                    ha="center",
                    va="bottom",
                    fontsize=8,
                    color=TEXT,
                    zorder=4,
                )
        # Highlight the semantic-removal category (index 1).
        ax.axvspan(
            1 * group - group / 2,
            1 * group + group / 2,
            color=highlight_color,
            alpha=0.06,
            zorder=0,
        )
        text, xy, xytext, color = annotate
        ax.annotate(
            text,
            xy=(xy[0] * group, xy[1]),
            xytext=(xytext[0] * group, xytext[1]),
            fontsize=9,
            color=color,
            ha="center",
            va="center",
            arrowprops=dict(
                arrowstyle="->",
                color=color,
                linewidth=1.3,
                shrinkA=2,
                shrinkB=4,
            ),
            zorder=6,
        )
        ax.set_xticks(x)
        ax.set_xticklabels(labels, fontsize=9)
        ax.set_xlim(-0.55, (len(labels) - 1) * group + 0.55)
        ax.set_ylim(0, 125)
        ax.set_yticks(np.arange(0, 101, 20))
        _neurips_axes(ax)
        if ylabel:
            ax.set_ylabel("Rate (%)", fontsize=12, labelpad=6)
        return b1, b2

    h_lab, h_b, h_a = _vals(hard, hard_map)
    l_lab, l_b, l_a = _vals(learned, learned_map)

    fig, axes = plt.subplots(
        1,
        2,
        figsize=(11.5, 4.6),
        sharey=True,
        gridspec_kw={"width_ratios": [0.9, 1.15]},
    )
    panel(
        axes[0],
        h_lab,
        h_b,
        h_a,
        BLUE,
        (
            "Semantic trigger removal\n"
            f"+{h_b[1] - h_b[0]:.1f} pp Bypass",
            (1, float(h_b[1])),
            (2.35, 92),
            BLUE,
        ),
        ylabel=True,
    )
    axes[0].set_title("(a) Method A — Hard-trigger ablation", fontsize=12, color=TEXT, pad=8)

    panel(
        axes[1],
        l_lab,
        l_b,
        l_a,
        RED,
        (
            "Semantic features removed\n100% Bypass",
            (1, float(l_b[1])),
            (2.85, 82),
            RED,
        ),
    )
    axes[1].set_title("(b) Method B — Feature ablation", fontsize=12, color=TEXT, pad=8)

    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        frameon=False,
        fontsize=11,
        loc="lower center",
        bbox_to_anchor=(0.5, 0.94),
        ncol=2,
        handlelength=1.4,
        columnspacing=1.6,
    )
    fig.tight_layout(pad=0.4, w_pad=1.0)
    fig.subplots_adjust(top=0.84, bottom=0.18)
    return _save(fig, out)


